#!/usr/bin/env python3
"""Generate Jekyll redirects so the existing main:/ Pages publisher is safe.

Original parallel-session files remain intact in the repository. GitHub's
legacy Jekyll build excludes them and emits these pages at their old URLs;
the custom artifact build emits equivalent redirects directly.
"""
from pathlib import Path
import shutil
from build_site import ROOT, legacy_paths, redirect_html

REDIRECTS = ROOT / 'redirects'
# These trees contain historical source editions, not the current planner.
EXCLUDE_TREES = ('assets', 'css', 'data', 'docs', 'js', 'site/alt', 'site/pages', 'scripts', 'tests', 'tools')
EXCLUDE_FILES = ('COORDINATION.md', 'README.md', 'EXECUTIVE-SUMMARY.md', 'research-notes.md', 'package.json')

def main():
    if REDIRECTS.exists():
        shutil.rmtree(REDIRECTS)
    REDIRECTS.mkdir()
    paths = legacy_paths()
    for old in paths:
        slug = old.replace('/', '__')
        (REDIRECTS / slug).write_text(f'---\npermalink: /{old}\n---\n' + redirect_html(old))
    files = [p for p in paths if not any(p == tree or p.startswith(tree + '/') for tree in EXCLUDE_TREES)]
    excluded = sorted(set(EXCLUDE_TREES + EXCLUDE_FILES + tuple(files)))
    (ROOT / '_config.yml').write_text(
        '# Keep historical source trees in Git, but never publish their superseded claims.\n'
        '# Generated by scripts/generate_legacy_redirects.py.\n'
        'exclude:\n' + ''.join(f'  - {name}\n' for name in excluded)
    )
    print(f'Generated {len(paths)} Jekyll-safe redirect pages')

if __name__ == '__main__':
    main()
