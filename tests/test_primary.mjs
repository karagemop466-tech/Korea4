import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../js/app.js', import.meta.url), 'utf8');
const context = { window: {}, document: { addEventListener() {} }, Intl, Date };
vm.createContext(context);
vm.runInContext(source.replace(/\}\)\(\);\s*$/, 'window.audit = { mergeIntervals, freeWindows, adjustedIntervals, todayPacific }; })();'), context);
const api = context.window.audit;
const merged = api.mergeIntervals([{start: 10, end: 20, category:'MLB'}, {start: 20, end: 30, category:'NFL'}]);
assert.equal(merged.length, 1);
assert.equal(merged[0].end, 30);
assert.equal(api.freeWindows(merged).reduce((n,r) => n+r.end-r.start, 0), 1420);
const fragment = {start:0, end:35, category:'MLB', status:'OFFICIAL_START_ESTIMATED_DURATION'};
assert.equal(api.adjustedIntervals([fragment])[0].end, 35, 'overnight fragment must not be extended to a new full game');
assert.match(api.todayPacific(), /^\d{4}-\d{2}-\d{2}$/);
assert(!source.includes('EXACT FREE WINDOW'));
assert(!source.includes('FREE ALL DAY — OFFICIAL PUBLISHED ROWS'));
assert(source.includes('UNKNOWN — no captured conflicts'));
console.log('Primary renderer: interval union, overnight fragments, Pacific today and uncertainty labels PASS.');
